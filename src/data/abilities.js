export const ABILITIES = {};
for (const [id, a] of Object.entries(HABILIDADES)) {
  ABILITIES[id] = { name: a.name, en: a.en, desc: EFEITOS[id] ?? '', active: id in EFEITOS };
}
// habilidades citadas na lógica que não estão nas espécies atuais (para futuras espécies)
const EXTRA = { filter: ['Filtro', 'Filter'], ironBarbs: ['Farpas de Ferro', 'Iron Barbs'], slushRush: ['Corrida na Neve', 'Slush Rush'],
  drought: ['Seca', 'Drought'], immunity: ['Imunidade', 'Immunity'], shellArmor: ['Armadura de Concha', 'Shell Armor'] };
for (const id of Object.keys(EFEITOS)) {
  if (!ABILITIES[id]) ABILITIES[id] = { name: EXTRA[id]?.[0] ?? id, en: EXTRA[id]?.[1] ?? id, desc: EFEITOS[id], active: true };
}

export function abilityInfo(id) { return ABILITIES[id]; }
